# Variables every tmuxp session file sets (``environment:``).  A command run on
# this machine inherits them from the launcher's own tmux session (e.g. the web
# console's adt4_console session: config=default, logging_key=base_station_console-
# default); run-adt4 must not see those, so the base station command drops them.
LEAKED_SESSION_VARS = ("config", "logging_key", "sim_time")
_CLEAN_SESSION_ENV = "env " + " ".join(f"-u {v}" for v in LEAKED_SESSION_VARS) + " "


class LaunchError(ValueError):
    """Raised when a launch plan is incomplete or inconsistent."""


@dataclass
class LaunchPlan:
    robots: list[str]  # may be empty: base station only (base_station + bs_session)
    session: str  # one session for every robot (see robot_session)
    experiment: str
    mode: str | None = None  # None (manual), "mapping", "relocalize"
    prior_path: str = ""
    prior_source: str | None = None  # machine that holds prior_path, if remote
    record: bool = False
    base_station: str | None = None
    bs_session: str | None = None
    # network the robot <-> base links use (None: zenoh.connect_network, else the
    # active network); see fleet_helpers.link_network
    link_network: str | None = None
    # "router" | "fleetlink" for this launch (None: fleet_defaults.fleet_link)
    link_mode: str | None = None
    # run the pre-launch checks (fleet.preflight); a NO-GO asks the user to confirm
    preflight: bool = True
    # platform ("spot" | "phoenix", see platform_of) -> session; a robot whose
    # platform is listed runs that session, the others ``session``
    sessions: dict[str, str] = field(default_factory=dict)
    # (re)launch only ``robots``: the base station's session, zenoh config and
    # fleetlink router/bridge are left alone; ``base_station`` is only the
    # reference for the checks and the "is the base running" warning
    robots_only: bool = False


def is_base_only(plan: LaunchPlan) -> bool:
    """No robots, only the base station's session (restart just the base)."""
    return not plan.robots and not plan.robots_only and bool(plan.base_station and plan.bs_session)


def with_link_mode(topo: dict | None, mode: str | None) -> dict | None:
    """``topo`` with ``fleet_defaults.fleet_link`` set to the launch's ``mode``
    (a copy; ``topo`` itself when ``mode`` is None).  Every step of a launch
    reads the mode from the topology (zenoh endpoints, each machine's fleet
    env, summaries), so one copy keeps them consistent."""
    if topo is None or not mode:
        return topo
    if mode not in FLEET_LINK_MODES:
        raise LaunchError(f"unknown link mode {mode!r} (one of {', '.join(FLEET_LINK_MODES)})")
    if mode == "fleetlink" and not fleetlink_base(topo):
        raise LaunchError("fleetlink mode needs fleet_defaults.fleetlink_base in the topology")
    out = dict(topo)
    out["fleet_defaults"] = {**(topo.get("fleet_defaults") or {}), "fleet_link": mode}
    return out


@dataclass
class Confirmation:
    kind: str  # "kill_sessions" | "overwrite_output"
    message: str
    required_text: str | None = None  # typed confirmation (e.g. "confirm")
    yes_label: str = "Yes"
    no_label: str = "No"
    detail: dict = field(default_factory=dict)


class LaunchCallbacks(Protocol):
    def log(self, level: str, text: str) -> None:
        """level: heading | info | dim | ok | warn | error"""

    def confirm(self, request: Confirmation) -> bool | None: ...

    def progress(self, machine: str, pct: float) -> None: ...

    def stop_local_zenohd(self) -> None: ...

    def local_zenohd_running(self) -> bool: ...


def session_launches_rviz(session: str | None, tmux_dir: pathlib.Path = TMUX_DIR) -> bool:
    """Whether ``session``'s tmuxp file starts RViz (``launch_rviz:=true``); the
    web-console sessions do not, so they need no namespaced RViz config.  An
    unknown session counts as starting it (the config is harmless)."""
    try:
        return "launch_rviz:=true" in (tmux_dir / f"{session}.yaml").read_text()
    except (OSError, TypeError):
        return True


def list_sessions(tmux_dir: pathlib.Path = TMUX_DIR) -> list[str]:
    return sorted(f.stem for f in tmux_dir.glob("*.yaml")) if tmux_dir.exists() else []


@lru_cache(maxsize=4)
def _manifest(path: str) -> dict:
    import yaml

    try:
        with open(path) as f:
            return yaml.safe_load(f) or {}
    except (OSError, yaml.YAMLError):
        return {}


def _as_list(v) -> list:
    if v is None:
        return []
    return [v] if isinstance(v, str) else list(v)


def _launch_groups(names, launch_configs: dict) -> set[str]:
    """Every launch-config group ``names`` expand to (themselves included)."""
    out: set[str] = set()
    todo = list(names)
    while todo:
        n = todo.pop()
        if n in out:
            continue
        out.add(n)
        todo += _as_list(launch_configs.get(n))
    return out


def session_mode(session: str | None, manifest: str | pathlib.Path = MANIFEST) -> str | None:
    """The launch mode a robot session belongs to: ``"relocalize"``, ``"mapping"``
    or ``None`` (a base-station / planning / unknown session).

    A session file is ``<experiment>-<config>`` (``tmux/autogenerated``); the
    experiment's ``launch_config`` in ``experiment_manifest.yaml`` decides: one that
    includes the ``relocalize`` group (``relocalize``, ``bag_relocalize``) loads the
    prior map, one built on ``robot_main`` without it (``map``, ``bag_map``, the
    regions / data-collection sessions) starts a fresh map and ignores ``-p``.
    A name that is not a generated session (unknown experiment or config) is
    ``None``: nothing to check it against.
    """
    if not session:
        return None
    name = str(session).removesuffix(".yaml")
    exp, sep, cfg = name.partition("-")
    if not sep:
        return None
    m = _manifest(str(manifest))
    entry = (m.get("experiments") or {}).get(exp)
    if not isinstance(entry, dict) or cfg not in _as_list(entry.get("config")):
        return None
    groups = _launch_groups(_as_list(entry.get("launch_config")), m.get("launch_configs") or {})
    if "relocalize" in groups:
        return "relocalize"
    if "robot_main" in groups:
        return "mapping"
    return None


def session_modes(sessions, manifest: str | pathlib.Path = MANIFEST) -> dict[str, str]:
    """``session -> "mapping" | "relocalize"`` for the robot sessions among
    ``sessions`` (others are left out)."""
    out = {}
    for s in sessions:
        mode = session_mode(s, manifest)
        if mode:
            out[s] = mode
    return out


def check_session_modes(plan: "LaunchPlan", runtime_config: dict, topo: dict | None) -> None:
    """Refuse a robot session of the other launch mode: a mapping session never
    loads the prior (relocalize mode), a relocalize session needs one and does not
    build a fresh map (mapping mode).  A plan without a mode, or a session that is
    not a generated robot session, is not checked."""
    if plan.mode not in LAUNCH_MODES:
        return
    bad = []
    for r in plan.robots:
        if r not in runtime_config:
            continue
        s = robot_session(plan, runtime_config[r], topo)
        mode = session_mode(s)
        if mode and mode != plan.mode:
            bad.append(f"{r} would run {s} (a {mode} session)")
    if bad:
        raise LaunchError(
            f"Launch mode is {plan.mode} but " + "; ".join(bad)
            + f". Pick a {plan.mode} session"
            + (" (e.g. spot_relocalize-relocalize)." if plan.mode == "relocalize" else ".")
        )


def session_platform(session: str | None) -> str | None:
    """The platform a robot session is made for, by its experiment name
    (``<experiment>-<config>``): ``spot*`` -> spot, ``phoenix*`` -> phoenix;
    ``None`` for any other session (base station, hand-made), which is not checked."""
    exp = str(session or "").removesuffix(".yaml").partition("-")[0]
    for platform in ("spot", "phoenix"):
        if exp.startswith(platform):
            return platform
    return None


def platform_equivalent(
    session: str | None,
    platform: str,
    topo: dict | None = None,
    mode: str | None = None,
    available=None,
) -> str | None:
    """``session`` for a robot of ``platform``: itself when it fits (or belongs to
    no platform); else the other platform's same session (``spot_relocalize-X`` <->
    ``phoenix_relocalize-X``) when that session file exists; else the platform's
    preset (``fleet_defaults.sessions``) for the session's launch mode (or
    ``mode``); ``None`` when there is no equivalent."""
    own = session_platform(session)
    if own is None or own == platform:
        return session
    name = str(session).removesuffix(".yaml")
    swapped = platform + name[len(own):]
    if swapped in (list_sessions() if available is None else available):
        return swapped
    presets = ((topo or {}).get("fleet_defaults") or {}).get("sessions") or {}
    preset = (presets.get(session_mode(session) or mode) or {}).get(platform)
    if preset and session_platform(preset) in (None, platform):
        return preset
    return None


def check_session_platforms(plan: "LaunchPlan", runtime_config: dict, topo: dict | None) -> None:
    """Refuse a robot session made for another platform: a phoenix (Husky) robot
    never runs a spot_* session and a Spot never a phoenix_* one."""
    bad = []
    for r in plan.robots:
        if r not in runtime_config:
            continue
        s = robot_session(plan, runtime_config[r], topo)
        sp, rp = session_platform(s), robot_platform(topo, runtime_config[r])
        if sp and sp != rp:
            bad.append(f"{r} (platform {rp}) would run {s} (a {sp} session)")
    if bad:
        raise LaunchError(
            "Session does not match the robot's platform: " + "; ".join(bad)
            + ". Pick a session of each robot's platform."
        )


def robot_platform(topo: dict | None, machine: dict) -> str:
    """``machine``'s platform by the shared rule (``platform_type`` from its
    topology entry, else from ``machine``; missing → spot, husky → phoenix).
    ``fleet_defaults.spot_platforms`` (platform ids) is no longer consulted."""
    entry = ((topo or {}).get("machines") or {}).get(machine.get("name"))
    return platform_of(entry or machine)


def robot_session(plan: LaunchPlan, machine: dict, topo: dict | None) -> str:
    """The session ``machine`` runs for ``plan``.

    ``plan.sessions`` (platform -> session) wins for the robot's platform.
    Otherwise ``plan.session`` is one session for the whole launch; when it is one of the
    per-platform presets in ``fleet_defaults.sessions`` (the launch mode's first),
    each robot gets that preset for *its* platform instead, so a hamilton + gauss
    launch runs spot-default on hamilton and phoenix-default on gauss.  Any other
    session (picked by hand, or a legacy single session from launch memory) runs
    on robots of its platform as given and maps to the other platform's
    equivalent (:func:`platform_equivalent`) on the others; one without an
    equivalent is returned as is and refused by :func:`check_session_platforms`.
    """
    platform = robot_platform(topo, machine)
    per_platform = (plan.sessions or {}).get(platform)
    if per_platform:
        return per_platform
    sessions = ((topo or {}).get("fleet_defaults") or {}).get("sessions") or {}
    modes = sorted(sessions, key=lambda m: m != plan.mode)
    for mode in modes:
        by_platform = sessions.get(mode) or {}
        if plan.session in by_platform.values():
            return by_platform.get(platform) or plan.session
    return platform_equivalent(plan.session, platform, topo, plan.mode) or plan.session


def default_selection(topo: dict, runtime_config: dict, mode: str, robots, local_ips):
    """Preset selections for ``mode`` from ``fleet_defaults`` in the topology.

    Returns dict(robots, session, sessions, base_station, bs_session).
    ``robots`` is the given list, or all online robots when it is None;
    ``session`` is the first robot's platform preset and ``sessions`` maps each
    robot to its own (what :func:`robot_session` launches).
    """
    defaults = topo.get("fleet_defaults", {})
    mode_sessions = defaults.get("sessions", {}).get(mode, {})

    if robots is None:
        robots = [
            m["name"]
            for m in runtime_config.values()
            if m["role"] == "robot" and m.get("online")
        ]
    first = next((runtime_config[n] for n in robots if n in runtime_config), None)
    if first is None:
        first = next(
            (
                m
                for m in runtime_config.values()
                if m["role"] == "robot" and m.get("online")
            ),
            None,
        )
    session = ""
    if first:
        session = mode_sessions.get(robot_platform(topo, first), "")
    sessions = {
        n: mode_sessions.get(robot_platform(topo, runtime_config[n]), "")
        for n in robots
        if n in runtime_config
    }

    base_station = next(
        (
            m["name"]
            for m in runtime_config.values()
            if m["role"] == "base_station" and m["ip"] in local_ips
        ),
        None,
    )
    return {
        "robots": list(robots),
        "session": session,
        "sessions": sessions,
        "base_station": base_station,
        "bs_session": defaults.get("base_station_session", "") or None,
    }


def prior_dest_path(prior_path: str, output_root: str) -> str:
    return f"{output_root}/prior_{pathlib.Path(prior_path).name}"


def fleet_env_prefix(machine_name: str, topo: dict | None, network: str | None = None) -> str:
    """``ADT4_FLEETLINK_MODE=<mode> `` carrying this launch's link mode to ``run-adt4``.

    run-adt4 takes only the mode from the environment and derives
    ``ADT4_FLEETLINK_CONNECT`` / ``_PORT`` from the machine's own topology.yaml (+
    address overlay), so ``network`` (a single robot-link network) cannot be
    passed on; it is accepted for the callers' signature and ignored.
    Empty without a topology (run-adt4 then uses its topology's mode).
    """
    if topo is None:
        return ""
    return f"ADT4_FLEETLINK_MODE={shlex.quote(fleet_link_mode(topo))} "


def build_robot_commands(
    plan: LaunchPlan,
    runtime_config: dict,
    output_root: str,
    topo: dict | None = None,
    prior_overrides: dict | None = None,
):
    """Return ``[(machine, remote_cmd), ...]`` for every selected robot.

    ``prior_overrides``: robot -> prior path on that robot, when Phase 1 found the
    prior run already there under another name (same run_id).
    """
    if not plan.robots:
        raise LaunchError("No robots selected.")
    _validate_common(plan)
    missing = [r for r in plan.robots if r not in runtime_config]
    if missing:
        raise LaunchError(f"Unknown robot(s): {', '.join(missing)}")
    if not plan.session:
        unset = sorted(
            {
                robot_platform(topo, runtime_config[r])
                for r in plan.robots
                if not robot_session(plan, runtime_config[r], topo)
            }
        )
        if unset:
            raise LaunchError(
                "No session selected"
                + (f" for {', '.join(unset)} robots." if plan.sessions else ".")
            )
    check_session_platforms(plan, runtime_config, topo)
    check_session_modes(plan, runtime_config, topo)

    # A prior that lives on a source machine reaches the others as prior_<name>
    dest_prior = (
        prior_dest_path(plan.prior_path, output_root)
        if plan.prior_path and plan.prior_source
        else plan.prior_path
    )
    out_dir = f"{output_root}/{plan.experiment}"
    record_flag = " -r" if plan.record else ""

    cmds = []
    for rname in plan.robots:
        m = runtime_config[rname]
        rprior = plan.prior_path if rname == plan.prior_source else dest_prior
        if prior_overrides and rname in prior_overrides:
            rprior = prior_overrides[rname]
        prior_flag = f" -p {_quote_path(rprior)}" if rprior else ""
        cmd = (
            f"{_WS_PREFIX}{fleet_env_prefix(m['name'], topo, plan.link_network)}{RUN_ADT4} "
            f"{shlex.quote(robot_session(plan, m, topo))} -n {shlex.quote(m['name'])} "
            f"-c {shlex.quote(m['platform_id'])} "
            f"-o {_quote_path(out_dir)} -y{prior_flag}{record_flag} "
            f'--tmuxp-args "-d"'
        )
        cmds.append((m, cmd))
    return cmds


def _validate_common(plan: LaunchPlan) -> None:
    if not plan.experiment:
        raise LaunchError("No experiment name provided.")
    if plan.mode == "relocalize" and not plan.prior_path:
        raise LaunchError(
            "Relocalize mode requires a prior map. Select one or press p to refresh."
        )


def validate_plan(
    plan: LaunchPlan,
    runtime_config: dict,
    output_root: str,
    topo: dict | None = None,
) -> list:
    """Raise :class:`LaunchError` for an incomplete plan; returns the robot
    commands (``[]`` for a base-station-only plan)."""
    if not is_base_only(plan):
        return build_robot_commands(plan, runtime_config, output_root, topo)
    _validate_common(plan)
    if plan.base_station not in runtime_config:
        raise LaunchError(f"Unknown base station: {plan.base_station}")
    return []


def build_base_station_command(
    bs_machine: dict,
    bs_session: str,
    output_root: str,
    experiment: str,
    rviz_path=None,
    topo: dict | None = None,
    prior_path: str | None = None,
) -> str:
    out_dir = _quote_path(f"{output_root}/{experiment}")
    platform = bs_machine.get("platform_id")
    config_flag = f" -c {shlex.quote(platform)}" if platform else ""
    rviz_flag = f" --rviz-config {shlex.quote(rviz_path)}" if rviz_path else ""
    # the base station publishes the prior (prior_dsg) and seeds Neo4j from it
    # (heracles); a launch is a fresh run, so seeding replaces what Neo4j held
    prior_flag = f" -p {_quote_path(prior_path)}" if prior_path else ""
    seed_env = "ADT4_NEO4J_SEED=true " if prior_path else ""
    return (
        f"{_WS_PREFIX}{_CLEAN_SESSION_ENV}{fleet_env_prefix(bs_machine['name'], topo)}"
        f"{seed_env}nohup {RUN_ADT4} "
        f"{shlex.quote(bs_session)} -n {shlex.quote(bs_machine['name'])}"
        f"{config_flag} -o {out_dir} -y{prior_flag}{rviz_flag} "
        f'--tmuxp-args "-d" '
        f">/dev/null 2>&1 &"
    )


def dry_run_lines(
    plan: LaunchPlan,
    runtime_config: dict,
    output_root: str,
    topo: dict | None = None,
    active_network: str | None = None,
):
    topo = with_link_mode(topo, plan.link_mode)
    cmds = validate_plan(plan, runtime_config, output_root, topo)
    lines = []
    if topo is not None:
        net = link_network(topo, plan.link_network, active_network)
        mode = fleet_link_mode(topo)
        how = "robots dial the fleetlink base" if mode == "fleetlink" else "base dials the robots"
        lines.append(f"Robot links: {net or '?'}, {mode} mode ({how}); console/ssh: {active_network or '?'}")
    if plan.prior_path and plan.prior_source:
        exp_name = pathlib.Path(plan.prior_path).name
        for m, _ in cmds:
            if m["name"] != plan.prior_source:
                lines.append(
                    f"Transfer prior map: {plan.prior_source} -> {m['name']} "
                    f"({exp_name} as prior_{exp_name})"
                )
        lines.append(
            f"Prior map path on targets: {prior_dest_path(plan.prior_path, output_root)}"
        )
    if plan.robots_only:
        bs = plan.base_station or "the base station"
        lines.append(
            f"Robots only: {bs}'s session, zenoh config and fleetlink router/bridge "
            "are not touched"
        )
        lines.append(
            f"Stop '{TMUX_SESSION_NAME}' on {', '.join(m['name'] for m, _ in cmds)} if running "
            "(Ctrl-C every pane so recordings close, then kill)"
        )
        lines.append(
            f"Existing {output_root}/{plan.experiment} on a robot (without per-run dirs) "
            f"is moved aside to {plan.experiment}_prev-<time>, never deleted"
        )
    lines += [f'ssh {m["user"]}@{m["ip"]} "{cmd}"' for m, cmd in cmds]
    if is_base_only(plan):
        bs = runtime_config[plan.base_station]
        prior = plan.prior_path
        if prior and plan.prior_source and plan.prior_source != bs["name"]:
            lines.append(f"Transfer prior map: {plan.prior_source} -> {bs['name']}")
            prior = prior_dest_path(plan.prior_path, output_root)
        lines.append(f"Base station only: restart '{TMUX_SESSION_NAME}' on {bs['name']}")
        cmd = build_base_station_command(
            bs, plan.bs_session, output_root, plan.experiment, None, topo, prior_path=prior
        )
        lines.append(f'ssh {bs["user"]}@{bs["ip"]} "{cmd}"')
    return lines


@dataclass
class LaunchDeps:
    """Side-effecting functions, injectable for tests."""

    ssh: Callable = ssh_cmd
    rsync: Callable = rsync_transfer
    deploy_zenoh: Callable = deploy_zenoh_config
    zenoh_endpoints: Callable = generate_zenoh_endpoints
    rviz: Callable = generate_namespaced_rviz
    session_rviz: Callable = session_launches_rviz
    parallel: Callable = run_parallel
    sleep: Callable = time.sleep
    local_ips: Callable = get_local_ips
    # scan(machine, root, only=None) -> run_scan identity entries, or None when the
    # machine cannot be scanned (then Phase 1 falls back to comparing names)
    scan: Callable | None = None


def scan_identities(deps, machine: dict, root: str, only=None, manifest=False):
    """Light ``run_scan`` (identity only) of ``root`` on ``machine``; None on failure.

    ``manifest``: entries also carry the file manifest digest and ``dsg_sig``.
    """
    if deps.scan is not None:
        if manifest:
            return deps.scan(machine, root, only, manifest=True)
        return deps.scan(machine, root, only)
    from dcist_launch_system.fleet.maps import parse_scan_output, remote_scan_command

    try:
        rc, out, _ = deps.ssh(
            machine["user"],
            machine["ip"],
            remote_scan_command(root, None, 0, only, light=True, manifest=manifest),
            timeout=30,
        )
    except Exception:  # noqa: BLE001
        return None
    if rc != 0:
        return None
    try:
        return parse_scan_output(out)
    except ValueError:
        return None


def prior_identity(prior_path, prior_source, runtime_config, deps) -> dict | None:
    """The prior run's scan entry (identity + origin) on its source machine."""
    src = runtime_config.get(prior_source)
    if not src or not prior_path:
        return None
    p = pathlib.PurePosixPath(prior_path)
    # with the manifest: a copy records it, and old unlabelled copies are matched by it
    runs = scan_identities(deps, src, str(p.parent), [p.name], manifest=True)
    if not runs:
        return None
    from dcist_launch_system.fleet.run_identity import canonical_id

    entry = runs[0]
    return entry if canonical_id(entry) else None


def ensure_prior_on(
    prior_path,
    prior_source,
    target,
    runtime_config,
    output_root,
    cb,
    deps,
    prior_entry: dict | None = None,
    images: bool = True,
):
    """Make the prior map available on ``target``; returns its path there (None = failed).

    ``images`` False (robots) leaves the prior's ``image_store/`` out of the copy.

    With the prior's identity (``prior_entry``) the target's runs are matched by
    run_id: a run already holding it (the original, an earlier ``prior_*`` copy, a
    copy under any name) is used as is.  ``prior_<name>`` taken by a different run is
    never merged into; a ``__N`` suffix is picked instead.  Without an identity
    (scan failed) the old rule applies: ``prior_<name>`` with hydra/ + roman/ counts.
    """
    from dcist_launch_system.fleet import run_identity as ri

    dest_path = prior_dest_path(prior_path, output_root)
    dest_name = pathlib.Path(dest_path).name
    prior_id = ri.canonical_id(prior_entry) if prior_entry else None
    runs = scan_identities(deps, target, output_root) if prior_id else None
    if runs is not None:
        for r in runs:
            if prior_id in ri.entry_ids(r) and all(
                d in r.get("subdirs", []) for d in ("hydra", "roman")
            ):
                path = f"{output_root}/{r['name']}"
                if _copy_map_differs(deps, target, output_root, r["name"], prior_entry):
                    cb.log(
                        "warn",
                        f"{target['name']}: {r['name']} has the prior's run id but a "
                        "different map (partial or changed copy); re-copying it",
                    )
                    return _transfer_prior(
                        prior_path, prior_source, target, path, runtime_config, cb, deps,
                        prior_entry, images,
                    )  # fmt: skip
                cb.log(
                    "dim",
                    f"{target['name']}: prior run already present as {r['name']} "
                    f"(run {prior_id[:8]}), no transfer",
                )
                cb.progress(target["name"], 100)
                return path
        same, how = _unlabelled_copy(deps, target, output_root, runs, dest_name, prior_entry)
        if same is not None:
            path = f"{output_root}/{same}"
            if how == "same_files":
                cb.log(
                    "dim",
                    f"{target['name']}: {same} has the prior's files (copied before "
                    "copies were labelled); labelled it, no transfer",
                )
                _mark_origin(
                    deps, target, path, prior_entry, prior_source, "all" if images else "none"
                )
                cb.progress(target["name"], 100)
                return path
            cb.log(
                "info",
                f"{target['name']}: {same} is an older copy of the prior (same scene "
                "graph); updating it in place",
            )
            return _transfer_prior(
                prior_path, prior_source, target, path, runtime_config, cb, deps,
                prior_entry, images,
            )  # fmt: skip
        existing = {r["name"]: ri.entry_ids(r) for r in runs if r.get("name")}
        dest_name, status = ri.choose_dest_name(dest_name, existing, prior_id)
        if status.startswith("collision"):
            cb.log(
                "warn",
                f"{target['name']}: {pathlib.Path(dest_path).name} holds a different "
                f"run; copying the prior to {dest_name} instead",
            )
        dest_path = f"{output_root}/{dest_name}"
    else:
        _, out, _ = deps.ssh(
            target["user"],
            target["ip"],
            f"test -d {_quote_path(dest_path + '/hydra')} && "
            f"test -d {_quote_path(dest_path + '/roman')} && echo OK",
            timeout=10,
        )
        if "OK" in out:
            cb.log("dim", f"{target['name']}: prior map already present ({dest_name})")
            cb.progress(target["name"], 100)
            return dest_path

    return _transfer_prior(
        prior_path, prior_source, target, dest_path, runtime_config, cb, deps, prior_entry,
        images,
    )  # fmt: skip


def _copy_map_differs(deps, target, output_root, name, prior_entry) -> bool:
    """True when ``target``'s run ``name`` provably holds a different map than the
    prior (``preflight.compare_prior`` NO-GO); unknown (scan failed) -> False."""
    from dcist_launch_system.fleet import preflight as pf

    found = scan_identities(deps, target, output_root, [name], manifest=True)
    if not found or not (prior_entry or {}).get("manifest"):
        return False
    return pf.compare_prior(target["name"], name, prior_entry, found[0]).status == pf.NOGO


def _unlabelled_copy(deps, target, output_root, runs, dest_name, prior_entry):
    """A ``prior_<name>[__N]`` dir on ``target`` with no origin record that holds the
    prior anyway (made before copies were labelled): ``(name, "same_files")`` when its
    file manifest equals the source's, ``(name, "same_dsg")`` when only the saved scene
    graph matches (an older copy: update it in place), else ``(None, None)``."""
    src_digest = ((prior_entry or {}).get("manifest") or {}).get("digest")
    src_dsg = (prior_entry or {}).get("dsg_sig")
    if not (src_digest or src_dsg):
        return None, None
    names = [
        r["name"]
        for r in runs
        if (r.get("name") == dest_name or str(r.get("name", "")).startswith(dest_name + "__"))
        and not r.get("origin")
        and (r.get("identity") or {}).get("source") == "fallback"
    ]
    if not names:
        return None, None
    found = scan_identities(deps, target, output_root, names, manifest=True) or []
    for r in found:
        if src_digest and (r.get("manifest") or {}).get("digest") == src_digest:
            return r["name"], "same_files"
    for r in found:
        if src_dsg and r.get("dsg_sig") == src_dsg:
            return r["name"], "same_dsg"
    return None, None


# A robot never reads the prior's image store (only the base's heracles/console do),
# and it is most of a map's size (5.3 of 5.6 GB for b45): robots get the map without it.
ROBOT_PRIOR_EXCLUDES = ["recorded_data/", "image_store/", "image_store.partial/"]
BASE_PRIOR_EXCLUDES = ["recorded_data/"]


def _mark_origin(deps, target, dest_path, prior_entry, prior_source, images="all"):
    """Write ``.adt4_origin.json`` so the next launch finds the copy by run_id."""
    from dcist_launch_system.fleet import run_identity as ri

    origin = ri.make_origin(dict(prior_entry), prior_source, images, "none")
    deps.ssh(
        target["user"],
        target["ip"],
        ri.remote_write_command(f"{dest_path}/{ri.ORIGIN}", origin),
        timeout=10,
    )


def _transfer_prior(
    prior_path, prior_source, target, dest_path, runtime_config, cb, deps, prior_entry,
    images=True,
):  # fmt: skip
    from dcist_launch_system.fleet import run_identity as ri

    dest_name = pathlib.Path(dest_path).name
    prior_id = ri.canonical_id(prior_entry) if prior_entry else None
    cb.log("info", f"Transferring prior map to {target['name']}...")
    src = runtime_config.get(prior_source)
    if not src:
        cb.log("error", f"Source machine '{prior_source}' not found in config.")
        return None

    ok, method, msg = deps.rsync(
        src["user"],
        src["ip"],
        prior_path,
        target["user"],
        target["ip"],
        dest_path,
        relay=False,
        exclude=list(BASE_PRIOR_EXCLUDES if images else ROBOT_PRIOR_EXCLUDES),
        progress_callback=lambda pct: cb.progress(target["name"], pct),
    )
    if not ok:
        cb.log("error", f"{target['name']}: prior map transfer FAILED: {msg}")
        return None
    if prior_id:  # mark the copy so the next launch finds it by run_id
        _mark_origin(
            deps, target, dest_path, prior_entry, prior_source, "all" if images else "none"
        )
    cb.progress(target["name"], 100)
    cb.log("ok", f"{target['name']}: prior map transferred to {dest_name} ({method})")
    return dest_path


def _running_experiment(out: str) -> str:
    """The experiment a session runs, from ``tmux show-environment ADT4_OUTPUT_DIR``."""
    for line in out.splitlines():
        if line.startswith("ADT4_OUTPUT_DIR="):
            return pathlib.PurePosixPath(line.split("=", 1)[1].strip()).name
    return ""


def _resolve_session_conflicts(targets, cb, deps) -> bool:
    def check(m):
        rc, out, _ = deps.ssh(
            m["user"],
            m["ip"],
            f"tmux has-session -t {TMUX_SESSION_NAME} 2>/dev/null && "
            f"(tmux show-environment -t {TMUX_SESSION_NAME} ADT4_OUTPUT_DIR 2>/dev/null; true)",
            timeout=5,
        )
        return (m["name"], _running_experiment(out)) if rc == 0 else None

    cb.log("dim", f"Checking for existing '{TMUX_SESSION_NAME}' sessions...")
    running = dict(r for _, r in deps.parallel(check, targets) if isinstance(r, tuple))
    conflicts = list(running)
    if not conflicts:
        return True

    what = [f"{n} (running {e})" if e else n for n, e in running.items()]
    cb.log(
        "warn",
        f"Session '{TMUX_SESSION_NAME}' already running on: {', '.join(what)}",
    )
    answer = cb.confirm(
        Confirmation(
            kind="kill_sessions",
            message=(
                f"Session '{TMUX_SESSION_NAME}' is already running on "
                f"{len(conflicts)} machine(s):\n{', '.join(what)}\n\n"
                "Terminate existing sessions and proceed?"
            ),
            yes_label="Yes, Terminate",
            no_label="No, Abort",
            detail={"machines": conflicts, "experiments": running},
        )
    )
    if not answer:
        cb.log("error", "Launch aborted by user.")
        return False
    for m in targets:
        if m["name"] in conflicts:
            cb.log("dim", f"Terminating session {TMUX_SESSION_NAME} on {m['name']}...")
            deps.ssh(
                m["user"],
                m["ip"],
                f"tmux kill-session -t {TMUX_SESSION_NAME}",
                timeout=5,
            )
    return True


def _resolve_output_conflicts(cmds, out_dir, experiment, cb, deps) -> bool:
    conflicts = []
    for m, _ in cmds:
        _, out, _ = deps.ssh(
            m["user"],
            m["ip"],
            f"test -d {_quote_path(out_dir)} && echo EXISTS",
            timeout=5,
        )
        if "EXISTS" in out:
            conflicts.append(m)
    if not conflicts:
        return True

    names = ", ".join(m["name"] for m in conflicts)
    cb.log("warn", f"{out_dir} already exists on: {names}")

    total_bytes = 0
    for m in conflicts:
        _, sz, _ = deps.ssh(
            m["user"],
            m["ip"],
            f"du -sb {_quote_path(out_dir)} 2>/dev/null | awk '{{print $1}}'",
            timeout=10,
        )
        try:
            total_bytes += int(sz.strip())
        except (ValueError, AttributeError):
            pass

    detail = {"machines": [m["name"] for m in conflicts], "bytes": total_bytes}
    if total_bytes >= _GB:
        size_str = f"{total_bytes / _GB:.1f} GB"
        cb.log(
            "error",
            f"Warning: existing data is ~{size_str}. Type 'confirm' to overwrite.",
        )
        request = Confirmation(
            kind="overwrite_output",
            message=(
                f"Output directory '{experiment}' already exists on:\n{names}\n\n"
                f"Total data at risk: ~{size_str}\n\n"
                "Type confirm below to overwrite and proceed."
            ),
            required_text="confirm",
            detail=detail,
        )
    else:
        request = Confirmation(
            kind="overwrite_output",
            message=(
                f"Output directory '{experiment}' already exists on:\n{names}\n\n"
                "Overwrite existing directories and launch?"
            ),
            yes_label="Yes, Overwrite",
            no_label="No, Keep",
            detail=detail,
        )

    answer = cb.confirm(request)
    if answer is None:
        cb.log("error", "Launch aborted — confirmation timed out or app closed.")
        return False
    if not answer:
        cb.log("error", "Launch aborted — existing directories preserved.")
        return False
    for m in conflicts:
        cb.log("dim", f"Removing {out_dir} on {m['name']}...")
        deps.ssh(m["user"], m["ip"], f"rm -rf {_quote_path(out_dir)}", timeout=15)
    return True


def run_launch(
    plan: LaunchPlan,
    *,
    topo: dict,
    active_network: str,
    runtime_config: dict,
    output_root: str,
    callbacks: LaunchCallbacks,
    deps: LaunchDeps | None = None,
) -> bool:
    """Run the full launch sequence. Blocking; returns True on success."""
    deps = deps or LaunchDeps()
    cb = callbacks
    try:
        topo = with_link_mode(topo, plan.link_mode)
        cmds = validate_plan(plan, runtime_config, output_root, topo)
    except LaunchError as e:
        cb.log("warn", str(e))
        return False
    if plan.robots_only:
        return _run_robots_only(plan, cmds, topo, runtime_config, output_root, cb, deps)

    bs_machine = runtime_config.get(plan.base_station) if plan.base_station else None
    if bs_machine and not plan.bs_session:
        bs_machine = None
    bs_is_robot = bool(bs_machine) and any(m["name"] == bs_machine["name"] for m, _ in cmds)
    bs_prior = plan.prior_path
    if bs_machine and plan.prior_path and plan.prior_source:
        if bs_machine["name"] != plan.prior_source:
            bs_prior = prior_dest_path(plan.prior_path, output_root)

    if plan.preflight:
        machines = [m for m, _ in cmds] + ([bs_machine] if bs_machine and not bs_is_robot else [])
        if not _run_preflight(machines, topo, output_root, bs_machine, cb, deps):
            return False

    # Phase 0: zenoh config on the base station only (star topology; robots listen).
    # In fleetlink mode the endpoints are [] (the deploy clears any robot links
    # left from router mode): robots reach the base only as fleetlink clients.
    if bs_machine:
        cb.log("heading", "Deploying zenoh config to base station...")
        if fleet_link_mode(topo) == "fleetlink":
            cb.log(
                "dim",
                "fleetlink mode: base router links to no robots; robots are "
                + fleetlink_summary(topo),
            )
        try:
            net = link_network(topo, plan.link_network, active_network)
            # base station only: link every robot (the running ones reconnect)
            linked = plan.robots or [
                n for n, m in runtime_config.items() if m.get("role") == "robot"
            ]
            endpoints = deps.zenoh_endpoints(
                topo, net, bs_machine["name"], robot_filter=linked
            )
            if fleet_link_mode(topo) != "fleetlink":
                cb.log("info", f"robot links over {net}: {', '.join(endpoints) or 'none'}")
                addrs = {r: (topo.get("machines", {}).get(r) or {}).get("addresses") or {} for r in linked}
                missing = [r for r in linked if net not in addrs[r]]
                if missing and net != active_network:
                    # no address on the link network: keep them reachable as before
                    endpoints += deps.zenoh_endpoints(
                        topo, active_network, bs_machine["name"], robot_filter=missing
                    )
                    cb.log("warn", f"{', '.join(missing)}: no {net} address in topology; linking over {active_network}")
            ok, msg = deps.deploy_zenoh(bs_machine["user"], bs_machine["ip"], endpoints)
            cb.log(
                "ok" if ok else "error",
                f"{bs_machine['name']}: {msg} ({len(endpoints)} ep)",
            )
            if not ok:
                cb.log("error", "ABORT: zenoh deploy failed on some machines.")
                return False
        except KeyError:
            cb.log("dim", f"{bs_machine['name']}: no address on {active_network}")

    # Phase 1: prior maps
    if plan.prior_path and plan.prior_source:
        cb.log("heading", "Phase 1: Ensuring prior maps on all robots...")
        from dcist_launch_system.fleet.run_identity import canonical_id

        prior_entry = prior_identity(
            plan.prior_path, plan.prior_source, runtime_config, deps
        )
        if prior_entry:
            cb.log(
                "dim",
                f"prior run id {canonical_id(prior_entry)} "
                f"({prior_entry['identity'].get('source')})",
            )
        overrides = {}
        default_dest = prior_dest_path(plan.prior_path, output_root)
        for m, _ in cmds:
            if m["name"] == plan.prior_source:
                continue
            path = ensure_prior_on(
                plan.prior_path,
                plan.prior_source,
                m,
                runtime_config,
                output_root,
                cb,
                deps,
                prior_entry,
                images=False,
            )
            if not path:
                cb.log("error", f"ABORT: could not transfer prior to {m['name']}")
                return False
            if path != default_dest:
                overrides[m["name"]] = path
        if bs_machine and not bs_is_robot and bs_machine["name"] != plan.prior_source:
            bs_prior = ensure_prior_on(
                plan.prior_path,
                plan.prior_source,
                bs_machine,
                runtime_config,
                output_root,
                cb,
                deps,
                prior_entry,
            )
            if not bs_prior:
                cb.log("error", f"ABORT: could not transfer prior to {bs_machine['name']}")
                return False
        if overrides:
            cmds = build_robot_commands(
                plan, runtime_config, output_root, topo, prior_overrides=overrides
            )
        if plan.preflight:
            loads = {m["name"]: (m, plan.prior_path if m["name"] == plan.prior_source else overrides.get(m["name"], default_dest)) for m, _ in cmds}
            if bs_machine and not bs_is_robot and bs_prior:
                loads[bs_machine["name"]] = (bs_machine, bs_prior)
            if not _verify_prior_maps(plan, runtime_config, loads, cb, deps):
                return False

    # Phase 1.5: running tmux sessions (the base station's too: a session left from
    # an earlier launch would keep running with the old prior, or none)
    targets = [m for m, _ in cmds]
    if bs_machine and not bs_is_robot:
        if _hosts_this_process(bs_machine, deps):
            cb.log(
                "warn",
                f"{bs_machine['name']}: '{TMUX_SESSION_NAME}' runs this launcher, so it "
                "is not restarted; restart the base station from a terminal to load "
                "the new prior",
            )
            bs_machine = None
            if not cmds:
                cb.log("error", "Base station only: nothing to launch.")
                return False
        else:
            targets.append(bs_machine)
    if not _resolve_session_conflicts(targets, cb, deps):
        return False

    # Phase 2: output dirs, then launch robots
    out_dir = f"{output_root}/{plan.experiment}"
    if cmds and not _resolve_output_conflicts(cmds, out_dir, plan.experiment, cb, deps):
        return False

    cb.log("heading", ("Phase 2: " if plan.prior_path else "") + "Launching...")
    all_ok = True
    for m, cmd in cmds:
        cb.log("info", f"Launching on {m['name']}...")
        rc, _, err = deps.ssh(m["user"], m["ip"], cmd, timeout=30)
        if rc == 0:
            cb.log("ok", f"{m['name']}: launched")
        else:
            all_ok = False
            cb.log("error", f"{m['name']}: FAILED (rc={rc}) {err}")

    # Phase 3: base station
    if bs_machine and not bs_is_robot:
        all_ok &= _launch_base_station(
            plan, bs_machine, output_root, cb, deps, topo, prior_path=bs_prior
        )

    cb.log("heading", "Launch sequence complete.")
    return all_ok


# robots-only relaunch: how long a robot's panes get to exit after Ctrl-C (bags
# close, hydra / ROMAN stop) before its session is killed
ROBOT_STOP_WAIT_S = 30.0
ROBOT_STOP_POLL_S = 2.0
_SHELLS = {"zsh", "bash", "sh", "fish", "dash"}


def _stop_session_cleanly(m, cb, deps, wait_s=ROBOT_STOP_WAIT_S, poll_s=ROBOT_STOP_POLL_S) -> bool:
    """Ctrl-C every pane of ``m``'s ``adt4_system`` session (a recording pane
    closes its bag), wait up to ``wait_s`` for the panes to drop back to their
    shells, then kill the session.  True once it is gone."""
    s = TMUX_SESSION_NAME
    rc, _, _ = deps.ssh(
        m["user"], m["ip"],
        f"tmux has-session -t {s} 2>/dev/null && "
        f"for p in $(tmux list-panes -s -t {s} -F '#{{pane_id}}'); do tmux send-keys -t $p C-c; done",
        timeout=10,
    )  # fmt: skip
    if rc != 0:
        cb.log("dim", f"{m['name']}: no '{s}' session running")
        return True
    cb.log("info", f"{m['name']}: sent Ctrl-C to every pane of '{s}'; waiting up to {wait_s:.0f} s")
    waited = 0.0
    busy: list[str] = []
    while waited < wait_s:
        deps.sleep(poll_s)
        waited += poll_s
        rc, out, _ = deps.ssh(
            m["user"], m["ip"], f"tmux list-panes -s -t {s} -F '#{{pane_current_command}}'", timeout=10
        )
        busy = [c for c in (out or "").split() if c not in _SHELLS] if rc == 0 else []
        if not busy:
            cb.log("ok", f"{m['name']}: every pane exited after {waited:.0f} s")
            break
    else:
        cb.log("warn", f"{m['name']}: still running after {wait_s:.0f} s ({', '.join(sorted(set(busy)))}); killing")
    rc, out, err = deps.ssh(m["user"], m["ip"], f"tmux kill-session -t {s}", timeout=10)
    if rc != 0 and "can't find session" not in (err or out or ""):
        rc2, _, _ = deps.ssh(m["user"], m["ip"], f"tmux has-session -t {s} 2>/dev/null", timeout=5)
        if rc2 == 0:
            cb.log("error", f"{m['name']}: could not kill '{s}': {err or out or rc}")
            return False
    cb.log("ok", f"{m['name']}: '{s}' stopped")
    return True


def move_aside_command(out_dir: str) -> str:
    """Shell: move an existing ``out_dir`` to ``<out_dir>_prev-<time>`` and print
    ``MOVED <new path>``.  A dir with per-run subdirs (``runs/``, run-adt4 that
    keeps every run in ``<exp>/runs/<run_id>``) is left in place."""
    return (
        f"d={_quote_path(out_dir)}; "
        'if [ -d "$d" ] && [ ! -e "$d/runs" ]; then '
        'n="${d}_prev-$(date +%Y%m%d-%H%M%S)"; '
        'while [ -e "$n" ]; do n="${n}x"; done; '
        'mv "$d" "$n" && echo "MOVED $n"; fi'
    )


def _move_aside_outputs(cmds, out_dir, cb, deps) -> dict | None:
    """Robots-only relaunch: keep every robot's previous run.  Returns robot ->
    new path of the moved dir ({} when nothing moved); None when a move failed."""
    moved = {}
    for m, _ in cmds:
        rc, out, err = deps.ssh(m["user"], m["ip"], move_aside_command(out_dir), timeout=30)
        line = next((ln for ln in (out or "").splitlines() if ln.startswith("MOVED ")), None)
        if rc != 0:
            cb.log("error", f"{m['name']}: could not move {out_dir} aside: {err or out or rc}")
            return None
        if line:
            moved[m["name"]] = line[len("MOVED "):].strip()
            cb.log("info", f"{m['name']}: kept the previous run: {out_dir} -> {moved[m['name']]}")
    return moved


def _base_running(bs, cb, deps) -> bool | None:
    try:
        rc, out, _ = deps.ssh(
            bs["user"], bs["ip"], f"tmux has-session -t {TMUX_SESSION_NAME} 2>/dev/null && echo OK", timeout=5
        )
    except Exception:  # noqa: BLE001
        return None
    return "OK" in (out or "")


def _run_robots_only(plan, cmds, topo, runtime_config, output_root, cb, deps) -> bool:
    """(Re)launch ``plan.robots`` only; see the module docstring."""
    bs = runtime_config.get(plan.base_station) if plan.base_station else None
    names = [m["name"] for m, _ in cmds]
    cb.log(
        "heading",
        f"Robots only: (re)launching {', '.join(names)}; the base station is not touched",
    )
    if bs is None:
        cb.log("warn", "No base station picked: robots need the base station for planning")
    else:
        up = _base_running(bs, cb, deps)
        if up is False:
            cb.log(
                "warn",
                f"{bs['name']}: no '{TMUX_SESSION_NAME}' session running. The robots launch "
                "anyway, but need the base station for planning; start it from Launch "
                "(base station only)",
            )
        elif up is None:
            cb.log("warn", f"{bs['name']}: cannot tell whether its session runs")
        else:
            cb.log("dim", f"{bs['name']}: base station session running, left alone")
    if fleet_link_mode(topo) != "fleetlink":
        cb.log(
            "warn",
            "router mode: the base's zenoh router is not reconfigured; it links to the "
            "robots of its last full launch",
        )

    if plan.preflight and not _run_preflight(
        [m for m, _ in cmds], topo, output_root, bs, cb, deps
    ):
        return False

    # Phase 1: prior map on the robots (none of the base station's)
    overrides = {}
    default_dest = prior_dest_path(plan.prior_path, output_root) if plan.prior_path else ""
    if plan.prior_path and plan.prior_source:
        cb.log("heading", "Phase 1: Ensuring the prior map on the robots...")
        prior_entry = prior_identity(plan.prior_path, plan.prior_source, runtime_config, deps)
        for m, _ in cmds:
            if m["name"] == plan.prior_source:
                continue
            path = ensure_prior_on(
                plan.prior_path, plan.prior_source, m, runtime_config, output_root, cb,
                deps, prior_entry, images=False,
            )  # fmt: skip
            if not path:
                cb.log("error", f"ABORT: could not transfer prior to {m['name']}")
                return False
            if path != default_dest:
                overrides[m["name"]] = path
        if plan.preflight:
            loads = {
                m["name"]: (m, plan.prior_path if m["name"] == plan.prior_source else overrides.get(m["name"], default_dest))
                for m, _ in cmds
            }  # fmt: skip
            if not _verify_prior_maps(plan, runtime_config, loads, cb, deps):
                return False

    # Phase 1.5: stop the robots' running sessions cleanly
    def check(m):
        rc, out, _ = deps.ssh(
            m["user"], m["ip"],
            f"tmux has-session -t {TMUX_SESSION_NAME} 2>/dev/null && "
            f"(tmux show-environment -t {TMUX_SESSION_NAME} ADT4_OUTPUT_DIR 2>/dev/null; true)",
            timeout=5,
        )  # fmt: skip
        return (m["name"], _running_experiment(out)) if rc == 0 else None

    running = dict(r for _, r in deps.parallel(check, [m for m, _ in cmds]) if isinstance(r, tuple))
    if running:
        what = [f"{n} (running {e})" if e else n for n, e in running.items()]
        answer = cb.confirm(
            Confirmation(
                kind="kill_sessions",
                message=(
                    f"Session '{TMUX_SESSION_NAME}' is running on {', '.join(what)}.\n\n"
                    "Stop it (Ctrl-C every pane, recordings close their bags) and relaunch? "
                    "The base station is not touched."
                ),
                yes_label="Yes, Stop and relaunch",
                no_label="No, Abort",
                detail={"machines": list(running), "experiments": running},
            )
        )
        if not answer:
            cb.log("error", "Launch aborted by user.")
            return False
        stopped = deps.parallel(
            lambda m: _stop_session_cleanly(m, cb, deps), [m for m, _ in cmds if m["name"] in running]
        )
        failed = [m["name"] for m, ok in stopped if ok is not True]
        if failed:
            cb.log("error", f"ABORT: could not stop the session on {', '.join(failed)}")
            return False

    # Phase 2: keep the previous output, then launch
    out_dir = f"{output_root}/{plan.experiment}"
    moved = _move_aside_outputs(cmds, out_dir, cb, deps)
    if moved is None:
        return False
    for name, new in moved.items():
        # a prior inside the moved dir (a robot relocalizing on its own last run)
        rprior = overrides.get(name) or (plan.prior_path if name == plan.prior_source else default_dest)
        if rprior and (rprior == out_dir or rprior.startswith(out_dir + "/")):
            overrides[name] = new + rprior[len(out_dir):]
    if overrides:
        cmds = build_robot_commands(plan, runtime_config, output_root, topo, prior_overrides=overrides)

    cb.log("heading", "Phase 2: Launching robots...")
    all_ok = True
    for m, cmd in cmds:
        cb.log("info", f"Launching on {m['name']}...")
        rc, _, err = deps.ssh(m["user"], m["ip"], cmd, timeout=30)
        if rc == 0:
            cb.log("ok", f"{m['name']}: launched")
        else:
            all_ok = False
            cb.log("error", f"{m['name']}: FAILED (rc={rc}) {err}")
    cb.log("heading", "Launch sequence complete.")
    return all_ok


_CHECK_LEVEL = {"go": "ok", "info": "dim", "warn": "warn", "nogo": "error"}


def _log_checks(checks, cb) -> None:
    for c in checks:
        cb.log(_CHECK_LEVEL.get(c.status, "info"), f"[{c.status.upper()}] {c.machine} / {c.name}: {c.detail}")


def _confirm_nogos(checks, stage, cb) -> bool:
    """True to go on: no NO-GO, or the user confirmed every one of them."""
    from dcist_launch_system.fleet import preflight as pf

    issues = pf.nogos(checks)
    if not issues:
        cb.log("ok", f"{stage}: GO")
        return True
    answer = cb.confirm(pf.nogo_confirmation(issues, stage))
    if not answer:
        cb.log("error", f"Launch aborted: {stage} NO-GO not confirmed.")
        return False
    cb.log("warn", f"{stage}: launching despite {len(issues)} NO-GO issue(s) (confirmed).")
    return True


def _run_preflight(machines, topo, output_root, bs_machine, cb, deps) -> bool:
    from dcist_launch_system.fleet import preflight as pf

    cb.log("heading", "Preflight: checking every machine...")
    checks = pf.run_checks(machines, topo, output_root, deps, reference=bs_machine["name"] if bs_machine else None)
    _log_checks(checks, cb)
    return _confirm_nogos(checks, "Preflight", cb)


def _verify_prior_maps(plan, runtime_config, loads, cb, deps) -> bool:
    """Every machine's prior (``loads``: name -> (machine, path)) holds the source map."""
    from dcist_launch_system.fleet import preflight as pf

    src = runtime_config.get(plan.prior_source)
    if not src:
        return True
    cb.log("heading", "Verifying the prior map on every machine...")
    checks = pf.verify_prior(src, plan.prior_path, loads, deps, scan_identities)
    _log_checks(checks, cb)
    return _confirm_nogos(checks, "Prior map", cb)


def _hosts_this_process(machine, deps) -> bool:
    """True if this process runs inside ``machine``'s ADT4 tmux session (e.g. the
    web console as a window of base_station_web), which killing it would end."""
    if not os.environ.get("TMUX") or machine.get("ip") not in deps.local_ips():
        return False
    try:
        out = subprocess.run(
            ["tmux", "display-message", "-p", "#S"],
            capture_output=True,
            text=True,
            timeout=5,
        ).stdout.strip()
    except (OSError, subprocess.SubprocessError):
        return False
    return out == TMUX_SESSION_NAME


def _launch_base_station(
    plan, bs_machine, output_root, cb, deps, topo=None, prior_path=None
) -> bool:
    cb.log("heading", "Launching base station...")
    if cb.local_zenohd_running():
        cb.log("dim", "Stopping fleet zenohd (base station will take over)...")
        cb.stop_local_zenohd()

    # mapping → first selected robot; relocalize → base station (publishes prior);
    # none for a session without RViz (the web console ones)
    rviz_path = None
    rviz_name = (
        bs_machine["name"]
        if plan.mode == "relocalize"
        else (plan.robots[0] if plan.robots else None)
    )
    if not deps.session_rviz(plan.bs_session):
        rviz_name = None
        cb.log("dim", f"{plan.bs_session}: no RViz in this session, no RViz config")
    if rviz_name:
        try:
            rviz_path = deps.rviz(rviz_name)
            cb.log("dim", f"RViz config: {rviz_path}")
        except Exception as e:
            cb.log("warn", f"RViz config generation failed: {e}")

    bs_cmd = build_base_station_command(
        bs_machine,
        plan.bs_session,
        output_root,
        plan.experiment,
        rviz_path,
        topo,
        prior_path=prior_path,
    )
    if prior_path:
        cb.log("dim", f"{bs_machine['name']}: prior {prior_path}")
    cb.log("dim", f"[{bs_machine['user']}@{bs_machine['ip']}] {bs_cmd}")
    rc, _, err = deps.ssh(bs_machine["user"], bs_machine["ip"], bs_cmd, timeout=60)

    # nohup & always returns 0; verify the tmux session actually started
    deps.sleep(3)
    _, tout, _ = deps.ssh(
        bs_machine["user"],
        bs_machine["ip"],
        f"tmux has-session -t {TMUX_SESSION_NAME} 2>/dev/null && echo OK",
        timeout=5,
    )
    if "OK" in tout:
        cb.log(
            "ok",
            f"{bs_machine['name']}: base station launched "
            f"(tmux session: {TMUX_SESSION_NAME})",
        )
        cb.log("dim", "Base station zenohd is now active on port 7447.")
        return True
    cb.log(
        "error",
        f"{bs_machine['name']}: tmux session '{TMUX_SESSION_NAME}' not found "
        f"after launch. rc={rc} {err}",
    )
    return False
