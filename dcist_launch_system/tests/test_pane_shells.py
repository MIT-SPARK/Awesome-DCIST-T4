"""Generated tmux sessions run every pane as its own process (no send-keys).

tmuxp types `shell_command_before` / pane commands with `tmux send-keys`, which
races slow shells; generate_configs.convert_to_pane_shells turns every pane into a
pane-level ``shell: zsh -ic '<setup> && <cmd>; exec zsh'`` instead.
"""

import os
import pathlib
import re
import shlex
import shutil
import subprocess
import sys

import pytest
import yaml

PKG = pathlib.Path(__file__).resolve().parents[1]
GEN_DIR = PKG / "config_generation"
COMPONENTS = GEN_DIR / "launch_components"
SESSIONS = sorted((PKG / "tmux" / "autogenerated").glob("*.yaml"))
SETUP = "source ${ADT4_WS}/install/setup.zsh"

sys.path.insert(0, str(GEN_DIR))
import generate_configs as gc  # noqa: E402

needs_zsh = pytest.mark.skipif(shutil.which("zsh") is None, reason="zsh missing")


def _load(path):
    with open(path) as f:
        return yaml.safe_load(f)


def _script(shell):
    """The pane's script after its Ctrl-C preamble (asserted present)."""
    argv = shlex.split(shell)
    assert argv[:2] == ["zsh", "-ic"], shell
    assert len(argv) == 3, shell
    assert argv[2].startswith(gc.PANE_PREAMBLE), shell
    return argv[2][len(gc.PANE_PREAMBLE) :]


def _component_cmd(component, window, index):
    for w in _load(COMPONENTS / f"{component}.yaml")["windows"]:
        if w["window_name"] == window:
            return w["panes"][index]
    raise KeyError(window)


def _session_pane(session, window, index):
    for w in _load(PKG / "tmux" / "autogenerated" / f"{session}.yaml")["windows"]:
        if w["window_name"] == window:
            return w["panes"][index]
    raise KeyError(window)


def test_sessions_exist():
    assert len(SESSIONS) > 10


@pytest.mark.parametrize("path", SESSIONS, ids=lambda p: p.stem)
def test_no_pane_relies_on_send_keys(path):
    session = _load(path)
    assert "shell_command_before" not in session
    assert "shell_command" not in session
    for window in session["windows"]:
        assert "shell_command_before" not in window, window["window_name"]
        assert "window_shell" not in window, window["window_name"]
        assert window["panes"], window["window_name"]
        for pane in window["panes"]:
            assert isinstance(pane, dict), (window["window_name"], pane)
            assert pane.get("shell", "").startswith("zsh -ic "), pane
            assert not pane.get("shell_command"), pane
            assert not pane.get("shell_command_before"), pane


@needs_zsh
@pytest.mark.parametrize("path", SESSIONS, ids=lambda p: p.stem)
def test_pane_scripts_parse_in_zsh(path):
    for window in _load(path)["windows"]:
        for pane in window["panes"]:
            script = _script(pane["shell"])
            ret = subprocess.run(
                ["zsh", "-f", "-n", "-c", script], capture_output=True, text=True
            )
            assert ret.returncode == 0, (window["window_name"], ret.stderr, script)


@pytest.mark.parametrize(
    "session,component,window,index,setup",
    [
        ("spot-default", "status", "status", 0, True),
        ("phoenix-default", "phoenix_real", "real_phoenix", 0, False),
        ("phoenix-default", "phoenix_real", "real_phoenix", 1, False),
    ],
)
def test_tricky_panes_round_trip(session, component, window, index, setup):
    """The pane command survives quoting byte for byte."""
    cmd = _component_cmd(component, window, index)
    script = _script(_session_pane(session, window, index)["shell"])
    before = f"{SETUP} && " if setup else ""
    assert script.startswith(f"{before}{cmd}; "), script
    # the command is also what lands in the interactive shell's history
    assert f"ADT4_PANE_CMD={shlex.quote(cmd)} exec zsh" in script
    assert script.endswith(" exec zsh")


def test_prepared_command_is_prefilled_not_run():
    cmd = _component_cmd("core", "core", 1)
    assert cmd.endswith("\\")
    script = _script(_session_pane("spot-default", "core", 1)["shell"])
    prepared = cmd.rstrip("\\").rstrip()
    assert script.startswith(f"{SETUP}; "), script  # setup only, cmd not run
    assert (
        f"ADT4_PANE_CMD={shlex.quote(prepared)} ADT4_PANE_PREFILL=1 exec zsh" in script
    )


def test_convert_handles_tmuxp_shorthands():
    session = {
        "shell_command_before": "echo session",
        "windows": [
            {
                "window_name": "w",
                "shell_command_before": ["echo a", {"cmd": "echo b"}],
                "panes": [
                    "echo one",
                    None,
                    "blank",
                    {"shell_command": ["echo x", "echo y"]},
                    {"shell": "already"},
                ],
            },
            {"window_name": "empty"},
        ],
    }
    out = gc.convert_to_pane_shells(session)
    assert "shell_command_before" not in out
    panes = out["windows"][0]["panes"]
    scripts = [_script(p["shell"]) for p in panes[:4]]
    assert scripts[0].startswith("echo session && echo a && echo b && echo one; ")
    assert scripts[1].startswith("echo session && echo a && echo b; ")
    assert scripts[2].startswith("echo session && echo a && echo b; ")
    assert scripts[3].startswith(
        "echo session && echo a && echo b && echo x && echo y; "
    )
    assert panes[4] == {"shell": "already"}
    assert _script(out["windows"][1]["panes"][0]["shell"]).startswith("echo session; ")


@needs_zsh
def test_pane_runs_with_session_env(tmp_path):
    """Run a generated pane with a fake workspace and ros2; check its argv."""
    ws = tmp_path / "ws"
    (ws / "install").mkdir(parents=True)
    (ws / "install" / "setup.zsh").write_text("export SOURCED_SETUP=1\n")
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    out = tmp_path / "argv.txt"
    ros2 = bin_dir / "ros2"
    ros2.write_text(
        f'#!/bin/sh\n{{ echo "setup=$SOURCED_SETUP"; for a in "$@"; do echo "$a"; done; }}'
        f" > {out}\n"
    )
    ros2.chmod(0o755)

    script = _script(_session_pane("spot-default", "status", 0)["shell"])
    env = {
        "PATH": f"{bin_dir}:{os.environ['PATH']}",
        "HOME": str(tmp_path),  # keep the user's ~/.zshrc out of the final exec zsh
        "ADT4_WS": str(ws),
        "ADT4_ROBOT_NAME": "hamilton",
        "ADT4_MONITOR_CONFIG": "{nodes_to_track: {}}",
    }
    subprocess.run(
        ["zsh", "-f", "-c", script],
        env=env,
        stdin=subprocess.DEVNULL,
        capture_output=True,
        timeout=30,
        check=False,
    )
    assert out.read_text().splitlines() == [
        "setup=1",
        "run", "ros_system_monitor", "ros_system_monitor",
        "--params", "{nodes_to_track: {}}",
        "--name", "hamilton",
        "--ros-args",
        "-r", "__ns:=/hamilton",
        "-r", "~/table_out:=/global/ros_system_monitor/table_in",
    ]  # fmt: skip


@needs_zsh
def test_pane_shell_rc_restores_user_zdotdir_and_history(tmp_path):
    """After its command, a pane is an interactive zsh that loads the user's rc
    files and has the command in its history."""
    home = tmp_path / "home"
    home.mkdir()
    (home / ".zshrc").write_text("export USER_RC_LOADED=1\n")
    ws = tmp_path / "ws"
    zdot = ws / "src/awesome_dcist_t4/dcist_launch_system/config_generation/pane_shell"
    zdot.mkdir(parents=True)
    for name in (".zshenv", ".zshrc"):
        shutil.copy(GEN_DIR / "pane_shell" / name, zdot / name)

    # a pane has a terminal; here stdin is a pipe, so ask for an interactive zsh
    script = gc.interactive_shell_cmd("echo pane-cmd").replace(
        "exec zsh", "exec zsh -i"
    )
    probe = 'print -r -- "rc=$USER_RC_LOADED zdotdir=${ZDOTDIR-unset}"; fc -ln -1\n'
    ret = subprocess.run(
        ["zsh", "-f", "-c", script],
        env={"PATH": os.environ["PATH"], "HOME": str(home), "ADT4_WS": str(ws)},
        input=probe,
        capture_output=True,
        text=True,
        timeout=30,
        check=False,
    )
    assert "rc=1 zdotdir=unset" in ret.stdout, (ret.stdout, ret.stderr)
    assert "echo pane-cmd" in ret.stdout, (ret.stdout, ret.stderr)


# --- process-matching guards ---------------------------------------------------
# A pane's shell is `zsh -ic '<its command>'`, so `pgrep -f X` / `pkill -f X` in a
# command also matches that pane's own shell whenever X appears in the command.
_PROC_MATCH_RE = re.compile(
    r"\b(?:pgrep|pkill)\b[^;|&]*?\s-\w*f\w*\s+(\"[^\"]*\"|'[^']*'|[^\s;|&]+)"
)


def _proc_patterns(cmd):
    for m in _PROC_MATCH_RE.finditer(cmd):
        yield m.group(1).strip("'\"")


def test_proc_pattern_extraction():
    assert list(
        _proc_patterns('if pgrep -f "a[b]c" >/dev/null; then pkill -f x-y; fi')
    ) == [
        "a[b]c",
        "x-y",
    ]


@pytest.mark.parametrize("path", SESSIONS, ids=lambda p: p.stem)
def test_no_pgrep_guard_matches_its_own_pane(path):
    for window in _load(path)["windows"]:
        for pane in window["panes"]:
            for pattern in _proc_patterns(_script(pane["shell"])):
                # what pgrep -f matches against: the pane process's argv, space-joined
                argv = " ".join(shlex.split(pane["shell"]))
                assert not re.search(pattern, argv), (window["window_name"], pattern)


def _bridge_pane():
    return _session_pane("base_station_web_repair-default", "fleetlink_base", 1)


@needs_zsh
@pytest.mark.parametrize("running", [False, True])
def test_fleetlink_bridge_guard(tmp_path, running):
    """The bridge starts unless a real bridge runs (not: unless its own pane runs)."""
    if shutil.which("pgrep") is None:
        pytest.skip("pgrep missing")
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    log = tmp_path / "ros2.log"
    (bin_dir / "ros2").write_text(f'#!/bin/sh\necho "$@" >> {log}\n')
    (bin_dir / "ros2").chmod(0o755)
    (tmp_path / "ws" / "install").mkdir(parents=True)
    (tmp_path / "ws" / "install" / "setup.zsh").write_text("")
    bridge = None
    if running:
        # a process whose argv looks like the installed bridge's
        fake = f"{tmp_path}/install/fleetlink/lib/fleetlink/fleetlink-bridge"
        bridge = subprocess.Popen(["bash", "-c", f"exec -a {fake} sleep 30"])
    try:
        # run the pane's script as its pane runs it: as `zsh -c '<script>'`, so its
        # own argv holds the whole command
        script = _script(_bridge_pane()["shell"]).split("; _adt4_zd=")[0]
        ret = subprocess.run(
            ["zsh", "-f", "-c", script],
            env={
                "PATH": f"{bin_dir}:{os.environ['PATH']}",
                "ADT4_FLEETLINK_MODE": "fleetlink",
                "ADT4_ROBOT_NAME": "willow",
                "ADT4_WS": str(tmp_path / "ws"),
                "sim_time": "false",
            },
            capture_output=True,
            text=True,
            timeout=30,
        )
    finally:
        if bridge:
            bridge.kill()
    if running:
        assert "fleetlink-bridge already running" in ret.stdout, ret
        assert not log.exists() or "fleetlink-bridge" not in log.read_text()
    else:
        assert "already running" not in ret.stdout, ret
        assert "run fleetlink fleetlink-bridge --ros-args" in log.read_text()
