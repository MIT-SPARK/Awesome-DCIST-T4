def test_supervise_turns_sighup_into_one_sigint(tmp_path):
    """tmux kill-session (SIGHUP) must reach the recorder as SIGINT (clean close)."""
    marker = tmp_path / "got"
    child = (
        "import signal, sys, time, pathlib\n"
        f"p = pathlib.Path({str(marker)!r})\n"
        "inherited = signal.getsignal(signal.SIGINT) is signal.default_int_handler\n"
        "def h(s, f):\n"
        "    p.write_text(signal.Signals(s).name); sys.exit(0)\n"
        "signal.signal(signal.SIGINT, h)\n"
        "signal.signal(signal.SIGHUP, h)\n"
        "pathlib.Path(str(p) + '.ready').write_text(str(inherited))\n"
        "time.sleep(30)\n"
    )
    wrapper = (
        "import sys\n"
        "from dcist_launch_system.record_topics import supervise\n"
        f"sys.exit(supervise([sys.executable, '-c', {child!r}]))\n"
    )
    env = {**os.environ, "PYTHONPATH": str(PKG / "src")}
    # started like a shell's background job: SIGINT ignored
    proc = subprocess.Popen(
        [sys.executable, "-c", wrapper],
        env=env,
        preexec_fn=lambda: signal.signal(signal.SIGINT, signal.SIG_IGN),
    )
    ready = pathlib.Path(str(marker) + ".ready")
    deadline = time.monotonic() + 15
    while not ready.exists() and time.monotonic() < deadline:
        time.sleep(0.05)
    assert ready.exists()
    # the recorder gets SIGINT with its default disposition, not the ignored one
    assert ready.read_text() == "True"
    proc.send_signal(signal.SIGHUP)
    assert proc.wait(timeout=15) == 0
    assert marker.read_text() == "SIGINT"


