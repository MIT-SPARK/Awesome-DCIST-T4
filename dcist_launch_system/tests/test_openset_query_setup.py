"""openset_query: opt-in install in python_setup.bash and the base station sessions that run it."""

import os
import pathlib
import subprocess
import sys

import pytest
import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
SETUP = ROOT / "install" / "python_setup.bash"
GENERATION = ROOT / "dcist_launch_system" / "config_generation"
AUTOGENERATED = ROOT / "dcist_launch_system" / "tmux" / "autogenerated"

sys.path.insert(0, str(GENERATION))
import generate_configs  # noqa: E402


def run_setup(tmp_path, *args, install_rc=0, weights_rc=0):
    """Run the installer with only the openset_query block active and a fake setup_env.sh."""
    script = tmp_path / "ws/src/awesome_dcist_t4/openset_query/setup_env.sh"
    script.parent.mkdir(parents=True)
    log = tmp_path / "setup_env.log"
    script.write_text(
        f'echo "${{1:-install}}" >> {log}\n'
        f'[ "${{1:-}}" = --weights ] && exit {weights_rc}\n'
        f"exit {install_rc}\n"
    )
    env = {
        **os.environ,
        "ADT4_WS": str(tmp_path / "ws"),
        "ADT4_ENV": str(tmp_path / "env"),
    }
    result = subprocess.run(
        ["bash", str(SETUP), "--no-roman", "--no-spark", "--no-console", *args],
        env=env,
        capture_output=True,
        text=True,
    )
    calls = log.read_text().splitlines() if log.exists() else []
    return result, calls


def test_openset_query_is_opt_in(tmp_path):
    result, calls = run_setup(tmp_path)
    assert result.returncode == 0, result.stderr
    assert calls == []


def test_openset_query_installs_then_fetches_weights(tmp_path):
    result, calls = run_setup(tmp_path, "--openset-query")
    assert result.returncode == 0, result.stderr
    assert calls == ["install", "--weights"]


def test_missing_weights_do_not_fail_the_install(tmp_path):
    result, calls = run_setup(tmp_path, "--openset-query", weights_rc=1)
    assert result.returncode == 0, result.stderr
    assert calls == ["install", "--weights"]
    assert "openset_query: model weights missing" in result.stdout


def test_failed_install_fails_and_skips_weights(tmp_path):
    result, calls = run_setup(tmp_path, "--openset-query", install_rc=1)
    assert result.returncode == 1
    assert calls == ["install"]
    assert "openset_query install failed" in result.stderr


def test_ci_skips_weights(tmp_path):
    result, calls = run_setup(tmp_path, "--is-ci", "--openset-query")
    assert result.returncode == 0, result.stderr
    assert calls == ["install"]


def neo4j_base_sessions():
    manifest = yaml.safe_load((GENERATION / "experiment_manifest.yaml").read_text())
    return {
        name: exp
        for name, exp in manifest["experiments"].items()
        if name.startswith("base_station") and "console_neo4j" in exp["launch_config"]
    }


# console-only session (start-adt4-console): no SAM3 server; the planning session started
# beside it runs the one openset_query server (a second copy would fight over its port/GPU)
CONSOLE_ONLY = {"base_station_console"}


def test_neo4j_base_sessions_run_openset_query():
    sessions = {k: v for k, v in neo4j_base_sessions().items() if k not in CONSOLE_ONLY}
    assert sessions
    for name, exp in sessions.items():
        assert "openset_query" in exp["launch_config"], name
        for config in exp["config"]:
            session = yaml.safe_load(
                (AUTOGENERATED / f"{name}-{config}.yaml").read_text()
            )
            (window,) = [
                w for w in session["windows"] if w["window_name"] == "openset_query"
            ]
            (pane,) = window["panes"]
            pane = generate_configs.pane_command(pane)  # panes are zsh -ic processes
            # without the sam3 venv the pane prints a hint instead of a traceback
            assert pane.startswith("if [ -x $ADT4_ENV/sam3/bin/openset-query-server ]")
            assert "openset_query not installed" in pane
            # live images only from the console's current run (its state file), never
            # a shared mirror folder holding earlier runs in their own frames
            assert "--live-state $HOME/adt4_output/console_live.json" in pane
            assert "--live-store-root" not in pane and "adt4_output/live" not in pane
            # credentials come from the session (HERACLES_NEO4J_USERNAME/PASSWORD)
            assert "HERACLES_NEO4J_PASSWORD" not in pane
            assert (
                session["environment"]["HERACLES_NEO4J_PASSWORD"]
                == "$ADT4_NEO4J_PASSWORD"
            )


@pytest.mark.parametrize("name", ["base_station", "base_station_repair"])
def test_file_map_base_sessions_do_not_run_openset_query(name):
    session = yaml.safe_load((AUTOGENERATED / f"{name}-default.yaml").read_text())
    assert "openset_query" not in {w["window_name"] for w in session["windows"]}
